from scipy.optimize import minimize
from itertools import product as iproduct

def run_nbi(n_points_per_dim=8, n_restarts=5):
    """
    Implementação do método NBI para n_factors objetivos.
    Usa Simplex Lattice para gerar os vetores de peso beta.
    """
    p = n_factors

    # ── Pontos âncora (payoff matrix) ────────────────────────────────────────
    anchors_x = []
    anchors_f = []
    for i in range(p):
        def obj_anchor(x, idx=i):
            return objective_for_minimization(x)[0, idx]
        best_val = np.inf
        best_x   = None
        for _ in range(n_restarts):
            x0 = BOUNDS_LOW + np.random.rand(5) * (BOUNDS_HIGH - BOUNDS_LOW)
            bounds = list(zip(BOUNDS_LOW, BOUNDS_HIGH))
            res = minimize(obj_anchor, x0, method='L-BFGS-B', bounds=bounds)
            if res.fun < best_val:
                best_val = res.fun
                best_x   = res.x
        anchors_x.append(best_x)
        anchors_f.append(objective_for_minimization(best_x)[0])

    F_anchors = np.array(anchors_f)  # shape (p, p)
    F_utopia  = F_anchors.min(axis=0)

    # Payoff normalizado (CHIM)
    F_range = F_anchors.max(axis=0) - F_anchors.min(axis=0)
    F_range[F_range == 0] = 1.0
    Phi = (F_anchors - F_utopia) / F_range  # shape (p, p)

    # Normal ao CHIM (quasi-normal)
    n_hat = -Phi.sum(axis=0)
    n_hat = n_hat / np.linalg.norm(n_hat)

    # ── Gerar vetores beta (Simplex Lattice) ─────────────────────────────────
    H = n_points_per_dim
    betas = []
    def gen_lattice(current, remaining, depth):
        if depth == p - 1:
            betas.append(current + [remaining / H])
            return
        for k in range(remaining + 1):
            gen_lattice(current + [k / H], remaining - k, depth + 1)
    gen_lattice([], H, 0)
    betas = np.array(betas)
    print(f'Vetores beta (NBI): {len(betas)}')

    # ── Resolver subproblema NBI para cada beta ───────────────────────────────
    pareto_x, pareto_f = [], []
    for beta in betas:
        start_point = sum(beta[i] * anchors_x[i] for i in range(p))
        start_point = np.clip(start_point, BOUNDS_LOW, BOUNDS_HIGH)

        def nbi_subproblem(xD):
            x  = xD[:5]
            D  = xD[5]
            Fval = objective_for_minimization(x)[0]
            F_norm = (Fval - F_utopia) / F_range
            chim_point = Phi.T @ beta
            eq_residuals = F_norm - chim_point - D * n_hat
            return float(eq_residuals @ eq_residuals) - D  # maximize D ~ minimize -D

        # Formulação alternativa — minimizar -D com restrições de igualdade
        def neg_D(xD):
            return -xD[5]

        def eq_constr(xD):
            x = xD[:5]
            D = xD[5]
            Fval = objective_for_minimization(x)[0]
            F_norm = (Fval - F_utopia) / F_range
            chim_point = Phi.T @ beta
            return F_norm - chim_point - D * n_hat

        x0_full = np.append(start_point, 1.0)
        bounds_full = list(zip(BOUNDS_LOW, BOUNDS_HIGH)) + [(None, None)]

        best_f = None
        best_val = np.inf
        for _ in range(n_restarts):
            x0_try = np.append(
                BOUNDS_LOW + np.random.rand(5)*(BOUNDS_HIGH - BOUNDS_LOW),
                1.0
            )
            try:
                res = minimize(
                    neg_D, x0_try,
                    method='SLSQP',
                    bounds=bounds_full,
                    constraints={'type': 'eq', 'fun': eq_constr},
                    options={'ftol': 1e-9, 'maxiter': 500}
                )
                if res.fun < best_val:
                    best_val = res.fun
                    best_f   = objective_for_minimization(res.x[:5])[0]
                    best_x   = res.x[:5]
            except Exception:
                pass

        if best_f is not None:
            pareto_x.append(best_x)
            pareto_f.append(best_f)

    return np.array(pareto_x), np.array(pareto_f), F_utopia, F_range

