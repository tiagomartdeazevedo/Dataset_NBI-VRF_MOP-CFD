def get_original_vrf_values(f_values, vrf_directions, vrf_cols):
    """Converts minimized objective values back to original VRF values."""
    original_vrf = f_values.copy()
    for i, vrf_name in enumerate(vrf_cols):
        if vrf_directions[vrf_name] == 1: # Was maximized, so it was multiplied by -1
            original_vrf[i] = -original_vrf[i]
    return original_vrf

def find_optimal_point_with_equal_weights(pareto_front_f, pareto_front_x, vrf_directions, vrf_cols):
    """Finds the optimal point from a Pareto front using equal weights (sum of objectives)."""
    if len(pareto_front_f) == 0:
        return None, None, None

    # Objectives are already in minimization form (maximization objectives are negative)
    # So, summing them up provides a scalarized value where lower is better
    scalarized_values = np.sum(pareto_front_f, axis=1)

    optimal_idx = np.argmin(scalarized_values)
    optimal_f_minimized = pareto_front_f[optimal_idx]
    optimal_x = pareto_front_x[optimal_idx]
    optimal_scalar_value = scalarized_values[optimal_idx]

    original_vrf = get_original_vrf_values(optimal_f_minimized, vrf_directions, vrf_cols)

    return original_vrf, optimal_x, optimal_scalar_value


