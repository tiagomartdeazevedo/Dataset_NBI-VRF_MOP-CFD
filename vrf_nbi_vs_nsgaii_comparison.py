# ── Definição dos objetivos para otimização (re-definido para garantir escopo) ──────────────────────────────────────────────────────────
# ATENÇÃO: Defina aqui a direção de otimização de cada VRF
# +1 = Maximizar (convertido para minimizar internamente: f' = -f)
# -1 = Minimizar
# Padrão: todos minimizados. Ajuste conforme os loadings do seu estudo.
# ─────────────────────────────────────────────────────────────────────────────
VRF_DIRECTIONS = {vrf_cols[i]: -1 for i in range(n_factors)}  # todos Min por padrão

# Exemplo de como ajustar:
VRF_DIRECTIONS['VRF1'] = -1   # Minimizar
VRF_DIRECTIONS['VRF2'] = +1   # Maximizar
VRF_DIRECTIONS['VRF3'] = -1   # Minimizar

# === START: predict_vrfs definition ===
def predict_vrfs(X_raw):
    """Recebe array (n, 5) nas escalas originais, retorna (n, n_factors)."""
    X_s = scaler_in.transform(X_raw)
    X_p = poly.transform(X_s)
    return np.column_stack([rsm_models[v].predict(X_p) for v in vrf_cols])
# === END: predict_vrfs definition ===

def objective_for_minimization(X_raw):
    """
    Retorna objetivos sempre como MINIMIZAÇÃO.
    Se VRF_DIRECTIONS[v] == +1 (Maximizar), inverte o sinal.
    """
    F = predict_vrfs(np.atleast_2d(X_raw))
    for i, v in enumerate(vrf_cols):
        if VRF_DIRECTIONS[v] == 1:
            F[:, i] = -F[:, i]
    return F


