def varimax_rotation(loadings, max_iter=1000, tol=1e-6):
    """Rotação Varimax sobre a matriz de loadings."""
    n, k = loadings.shape
    rotation = np.eye(k)
    for _ in range(max_iter):
        old = rotation.copy()
        for i in range(k):
            for j in range(i+1, k):
                L = loadings @ rotation
                u = L[:, i]**2 - L[:, j]**2
                v = 2 * L[:, i] * L[:, j]
                A = np.sum(u)
                B = np.sum(v)
                C = np.sum(u**2 - v**2)
                D = np.sum(2 * u * v)
                num = D - 2*A*B/n
                den = C - (A**2 - B**2)/n
                if abs(den) < 1e-12:
                    continue
                angle = 0.25 * np.arctan2(num, den)
                c, s = np.cos(angle), np.sin(angle)
                rot_ij = np.eye(k)
                rot_ij[i, i] =  c; rot_ij[i, j] = -s
                rot_ij[j, i] =  s; rot_ij[j, j] =  c
                rotation = rotation @ rot_ij
        if np.max(np.abs(rotation - old)) < tol:
            break
    return rotation

