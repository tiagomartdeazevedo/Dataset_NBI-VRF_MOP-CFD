# Certificar que a função spread_delta está disponível. Se ela foi definida em uma célula anterior e o kernel foi resetado,
# ela pode não estar no ambiente global. Copiamos ela aqui por segurança.
def spread_delta(F):
    """
    Spread (Δ) de Deb et al. (2002).
    Mede uniformidade da distribuição na fronteira Pareto.
    Δ → 0: distribuição perfeita; Δ → 1: distribuição concentrada.

    Para > 2 objetivos: usa distância ao vizinho mais próximo em vez de
    distâncias extremas por objetivo (generalização de Schott 1995).
    """
    n = len(F)
    if n < 2:
        return np.nan

    D = cdist(F, F)
    np.fill_diagonal(D, np.inf)
    d_nn = D.min(axis=1)  # distância ao vizinho mais próximo

    extreme_idx = [F[:, j].argmin() for j in range(F.shape[1])]
    extreme_idx = list(set(extreme_idx))

    d_extreme = d_nn[extreme_idx]

    internal_mask = np.ones(n, dtype=bool)
    internal_mask[extreme_idx] = False
    d_internal = d_nn[internal_mask]

    if len(d_internal) == 0:
        return np.nan

    d_mean = d_internal.mean()
    numerator   = d_extreme.sum() + np.abs(d_internal - d_mean).sum()
    deno = d_extreme.sum() + len(d_internal) * d_mean

    return numerator / deno if deno > 0 else np.nan


